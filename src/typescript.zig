//! TypeScript for a binding type, from the same Zig type the dispatcher uses
//! (methods.zig, codec.zig):
//!
//!   bool                    boolean
//!   integers, floats        number; bigint for integers past 53 bits passed
//!                           directly (arguments, sync results)
//!   []const u8              string
//!   slices, arrays          T[]
//!   structs                 interface (inline object type when anonymous)
//!   enums                   union of string literals
//!   union(enum)             { tag: "..."; value: ... } | ...
//!   ?T                      T | null
//!   error sets              PlumeError with the error's name as its code
//!
//! `module` is bindings.ts: the types, and the binding object with Zig errors
//! turned into PlumeError. `declarations` is bindings.d.ts: the same types and
//! the global object, for pages that do not import modules.

const std = @import("std");
const methods = @import("methods.zig");

pub const Kind = enum { module, declarations };

const Writer = std.Io.Writer;

pub fn write(comptime T: type, comptime name: []const u8, kind: Kind, w: *Writer) Writer.Error!void {
    const bound = comptime methods.of(T);
    const exported = if (kind == .module) "export " else "";

    try w.print("// Generated by Plume from the Zig type {s}: do not edit.\n\n", .{name});

    if (kind == .module) {
        try w.writeAll(
            \\/** A Zig error from a binding: the error's name in `code`. */
            \\export class PlumeError<Code extends string = string> extends Error {
            \\  readonly code: Code;
            \\  constructor(code: Code, message?: string) {
            \\    super(message ?? code);
            \\    this.name = "PlumeError";
            \\    this.code = code;
            \\  }
            \\}
            \\
            \\
        );
    }

    // The named types the methods use.
    const named = comptime collectAll(T, bound);
    inline for (named) |N| {
        try writeDeclaration(w, N, exported);
        try w.writeAll("\n");
    }

    // The error names each method may fail with.
    try w.print("{s}interface {s}Errors {{\n", .{ exported, name });
    inline for (bound) |method| {
        try w.print("  {s}: ", .{method.name});
        if (comptime methods.errorNames(T, method.name)) |errors| {
            if (errors.len == 0) {
                try w.writeAll("string");
            } else inline for (errors, 0..) |error_name, i| {
                if (i > 0) try w.writeAll(" | ");
                try w.print("\"{s}\"", .{error_name});
            }
        } else try w.writeAll("never");
        try w.writeAll(";\n");
    }
    try w.writeAll("}\n\n");

    // The bindings.
    try w.print("{s}interface {s}Bindings {{\n", .{ exported, name });
    inline for (bound) |method| {
        if (comptime methods.errorNames(T, method.name) != null)
            try w.print("  /** Fails with PlumeError<{s}Errors[\"{s}\"]>. */\n", .{ name, method.name });
        try w.print("  {s}(", .{method.name});
        try writeParams(w, T, method.name);
        try w.writeAll("): ");
        const R = methods.Result(T, method.name);
        if (method.is_async) {
            try w.writeAll("Promise<");
            try writeType(w, R, false);
            try w.writeAll(">");
        } else try writeType(w, R, true);
        try w.writeAll(";\n");
    }
    try w.writeAll("}\n\n");

    switch (kind) {
        .declarations => try w.print("declare const {s}: {s}Bindings;\n", .{ name, name }),
        .module => {
            try w.print(
                \\const native: any = (globalThis as any).{s};
                \\
                \\function plumeError(error: unknown): unknown {{
                \\  if (error instanceof Error && error.message.startsWith("plume:")) {{
                \\    const [code, ...detail] = error.message.slice(6).split(": ");
                \\    return new PlumeError(code, detail.length ? detail.join(": ") : code);
                \\  }}
                \\  return error;
                \\}}
                \\
                \\export const {s}: {s}Bindings = {{
                \\
            , .{ name, name, name });
            inline for (bound) |method| {
                const count = comptime methods.jsParams(T, method.name).len;
                try w.print("  {s}(", .{method.name});
                inline for (0..count) |i| {
                    if (i > 0) try w.writeAll(", ");
                    try w.print("arg{d}", .{i + 1});
                }
                try w.writeAll(") {\n");
                if (method.is_async) {
                    try w.print("    return native.{s}(", .{method.name});
                    try writeArgs(w, count);
                    try w.writeAll(").catch((error: unknown) => { throw plumeError(error); });\n");
                } else {
                    try w.print("    try {{ return native.{s}(", .{method.name});
                    try writeArgs(w, count);
                    try w.writeAll("); } catch (error) { throw plumeError(error); }\n");
                }
                try w.writeAll("  },\n");
            }
            try w.writeAll("};\n");
        },
    }
}

fn writeParams(w: *Writer, comptime T: type, comptime name: []const u8) Writer.Error!void {
    const params = comptime methods.jsParams(T, name);
    inline for (params, 0..) |P, i| {
        if (i > 0) try w.writeAll(", ");
        try w.print("arg{d}: ", .{i + 1});
        try writeType(w, P, true);
    }
}

fn writeArgs(w: *Writer, count: usize) Writer.Error!void {
    for (0..count) |i| {
        if (i > 0) try w.writeAll(", ");
        try w.print("arg{d}", .{i + 1});
    }
}

// ---- Types ----

/// Anonymous containers are written inline; named ones get a declaration.
fn isNamed(comptime X: type) bool {
    const type_name = @typeName(X);
    return switch (@typeInfo(X)) {
        .@"struct" => |info| !info.is_tuple and std.mem.indexOf(u8, type_name, "__struct_") == null,
        .@"enum" => std.mem.indexOf(u8, type_name, "__enum_") == null,
        .@"union" => std.mem.indexOf(u8, type_name, "__union_") == null,
        else => false,
    };
}

/// The TypeScript name of a named type: its last component, as an identifier.
fn typeName(comptime X: type) []const u8 {
    comptime {
        const full = @typeName(X);
        const short = if (std.mem.lastIndexOfScalar(u8, full, '.')) |dot| full[dot + 1 ..] else full;
        var result: [short.len]u8 = undefined;
        for (short, &result) |c, *slot|
            slot.* = if (std.ascii.isAlphanumeric(c) or c == '_') c else '_';
        const final = result;
        return &final;
    }
}

fn contains(comptime list: []const type, comptime X: type) bool {
    for (list) |item| {
        if (item == X) return true;
    }
    return false;
}

fn collectAll(comptime T: type, comptime bound: []const methods.Method) []const type {
    var list: []const type = &.{};
    for (bound) |method| {
        for (methods.jsParams(T, method.name)) |P| list = collect(list, P);
        list = collect(list, methods.Result(T, method.name));
    }
    return list;
}

/// `list` with the named types `X` uses (itself included), each once.
fn collect(comptime list: []const type, comptime X: type) []const type {
    switch (@typeInfo(X)) {
        .optional => |info| return collect(list, info.child),
        .pointer => |info| return switch (info.size) {
            .slice => if (info.child == u8) list else collect(list, info.child),
            .one => collect(list, info.child),
            else => list,
        },
        .array => |info| return if (info.child == u8) list else collect(list, info.child),
        .@"struct", .@"enum", .@"union" => {
            if (contains(list, X))
                return list;
            var result = list;
            if (isNamed(X))
                result = result ++ [_]type{X};
            switch (@typeInfo(X)) {
                .@"struct" => |info| for (info.field_types) |F| {
                    result = collect(result, F);
                },
                .@"union" => |info| for (info.field_types) |F| {
                    result = collect(result, F);
                },
                else => {},
            }
            return result;
        },
        else => return list,
    }
}

fn writeDeclaration(w: *Writer, comptime X: type, exported: []const u8) Writer.Error!void {
    switch (@typeInfo(X)) {
        .@"struct" => {
            try w.print("{s}interface {s} ", .{ exported, comptime typeName(X) });
            try writeObject(w, X, "\n", "  ");
            try w.writeAll("\n");
        },
        .@"enum" => {
            try w.print("{s}type {s} = ", .{ exported, comptime typeName(X) });
            try writeEnum(w, X);
            try w.writeAll(";\n");
        },
        .@"union" => {
            try w.print("{s}type {s} =", .{ exported, comptime typeName(X) });
            const info = @typeInfo(X).@"union";
            inline for (info.field_names, info.field_types) |field, F| {
                try w.writeAll("\n  | ");
                try writeVariant(w, field, F);
            }
            try w.writeAll(";\n");
        },
        else => unreachable,
    }
}

fn writeObject(w: *Writer, comptime X: type, comptime newline: []const u8, comptime indent: []const u8) Writer.Error!void {
    const info = @typeInfo(X).@"struct";
    try w.writeAll("{" ++ (if (newline.len > 0) newline else " "));
    inline for (info.field_names, info.field_types) |field, F| {
        try w.print(indent ++ "{s}: ", .{field});
        try writeType(w, F, false);
        try w.writeAll(";" ++ (if (newline.len > 0) newline else " "));
    }
    try w.writeAll("}");
}

fn writeEnum(w: *Writer, comptime X: type) Writer.Error!void {
    inline for (@typeInfo(X).@"enum".field_names, 0..) |field, i| {
        if (i > 0) try w.writeAll(" | ");
        try w.print("\"{s}\"", .{field});
    }
}

fn writeVariant(w: *Writer, comptime field: []const u8, comptime F: type) Writer.Error!void {
    try w.print("{{ tag: \"{s}\"", .{field});
    if (F != void) {
        try w.writeAll("; value: ");
        try writeType(w, F, false);
    }
    try w.writeAll(" }");
}

/// Whether the type is written with "|" at its top level (needs parentheses
/// before "[]").
fn isUnionLike(comptime X: type) bool {
    return switch (@typeInfo(X)) {
        .optional => true,
        .@"enum", .@"union" => !isNamed(X),
        else => false,
    };
}

/// `direct`: passed as an argument or sync result itself (not inside JSON),
/// where integers past 53 bits are BigInts.
fn writeType(w: *Writer, comptime X: type, comptime direct: bool) Writer.Error!void {
    switch (@typeInfo(X)) {
        .void => try w.writeAll("void"),
        .bool => try w.writeAll("boolean"),
        .int => |info| {
            const exact = if (info.signedness == .unsigned) info.bits <= 53 else info.bits <= 54;
            try w.writeAll(if (exact or !direct) "number" else "bigint");
        },
        .comptime_int, .float, .comptime_float => try w.writeAll("number"),
        .optional => |info| {
            try writeElement(w, info.child);
            try w.writeAll(" | null");
        },
        .pointer => |info| switch (info.size) {
            .slice => if (info.child == u8) try w.writeAll("string") else {
                try writeElement(w, info.child);
                try w.writeAll("[]");
            },
            .one => switch (@typeInfo(info.child)) {
                .array => |array| if (array.child == u8) try w.writeAll("string") else try writeType(w, info.child, direct),
                else => try writeType(w, info.child, direct),
            },
            else => @compileError("no TypeScript type for " ++ @typeName(X)),
        },
        .array => |info| {
            try writeElement(w, info.child);
            try w.writeAll("[]");
        },
        .@"struct", .@"enum", .@"union" => if (isNamed(X)) try w.writeAll(comptime typeName(X)) else switch (@typeInfo(X)) {
            .@"struct" => try writeObject(w, X, "", ""),
            .@"enum" => try writeEnum(w, X),
            .@"union" => |info| inline for (info.field_names, info.field_types, 0..) |field, F, i| {
                if (i > 0) try w.writeAll(" | ");
                try writeVariant(w, field, F);
            },
            else => unreachable,
        },
        else => @compileError("no TypeScript type for " ++ @typeName(X)),
    }
}

fn writeElement(w: *Writer, comptime X: type) Writer.Error!void {
    if (isUnionLike(X)) {
        try w.writeAll("(");
        try writeType(w, X, false);
        try w.writeAll(")");
    } else try writeType(w, X, false);
}

// ---- Tests ----

const Kind2 = enum { file, folder };
const Shape = union(enum) { circle: f64, none };
const FileEntry = struct {
    name: []const u8,
    size: u64,
    kind: Kind2,
    shape: Shape,
    tags: []const []const u8,
    parent: ?[]const u8,
    position: struct { x: i32, y: i32 },
};

const Files = struct {
    pub const async_methods = .{"list"};
    pub fn greet(self: *Files, name: []const u8) error{Empty}![]const u8 {
        _ = self;
        return name;
    }
    pub fn count(self: *Files, big: u64, small: u32) u64 {
        _ = self;
        return big + small;
    }
    pub fn list(self: *Files, allocator: std.mem.Allocator, dir: []const u8, kinds: []const ?Kind2) error{ NotFound, AccessDenied }![]FileEntry {
        _ = self;
        _ = allocator;
        _ = dir;
        _ = kinds;
        return &.{};
    }
};

test "bindings.ts for a binding type" {
    var out: std.Io.Writer.Allocating = .init(std.testing.allocator);
    defer out.deinit();
    try write(Files, "Files", .module, &out.writer);
    const ts = out.written();
    const expected = [_][]const u8{
        "export class PlumeError<Code extends string = string> extends Error {",
        "export interface FileEntry {\n  name: string;\n  size: number;\n  kind: Kind2;\n  shape: Shape;\n  tags: string[];\n  parent: string | null;\n  position: { x: number; y: number; };\n}",
        "export type Kind2 = \"file\" | \"folder\";",
        "export type Shape =\n  | { tag: \"circle\"; value: number }\n  | { tag: \"none\" };",
        // Zig orders an error set's names alphabetically.
        "export interface FilesErrors {\n  greet: \"Empty\";\n  count: never;\n  list: \"AccessDenied\" | \"NotFound\";\n}",
        "  greet(arg1: string): string;",
        "  count(arg1: bigint, arg2: number): bigint;",
        "  list(arg1: string, arg2: (Kind2 | null)[]): Promise<FileEntry[]>;",
        "const native: any = (globalThis as any).Files;",
        "    try { return native.greet(arg1); } catch (error) { throw plumeError(error); }",
        "    return native.list(arg1, arg2).catch((error: unknown) => { throw plumeError(error); });",
    };
    for (expected) |part| {
        if (std.mem.indexOf(u8, ts, part) == null) {
            std.debug.print("missing:\n{s}\n\nin:\n{s}\n", .{ part, ts });
            return error.TestUnexpectedResult;
        }
    }
}

test "bindings.d.ts declares the global object" {
    var out: std.Io.Writer.Allocating = .init(std.testing.allocator);
    defer out.deinit();
    try write(Files, "Files", .declarations, &out.writer);
    const dts = out.written();
    try std.testing.expect(std.mem.indexOf(u8, dts, "declare const Files: FilesBindings;") != null);
    try std.testing.expect(std.mem.indexOf(u8, dts, "interface FileEntry {") != null);
    try std.testing.expect(std.mem.indexOf(u8, dts, "export ") == null);
}
