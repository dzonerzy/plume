fn writeEvents(w: *Writer, comptime T: type, comptime name: []const u8, kind: Kind) Writer.Error!void {
    const exported = if (kind == .module) "export " else "";
    try w.writeAll("// The page runtime: the window, dialogs, clipboard, screens and menus.\n");
    inline for (runtime_declarations) |declaration| try w.print("{s}{s}\n", .{ exported, declaration });
    try w.writeAll("\n");
    if (EventsOf(T)) |E| {
        try w.print("/** The events of {s} (its Events): names and data. */\n{s}interface {s}Events {{\n", .{ name, exported, name });
        const info = @typeInfo(E).@"struct";
        inline for (info.field_names, info.field_types) |field, F| {
            try w.print("  \"{s}\": ", .{field});
            try writeType(w, F, false);
            try w.writeAll(";\n");
        }
        try w.writeAll("}\n\n");
    } else {
        try w.print("/** {s} declares no Events: any name, any data. */\n{s}type {s}Events = Record<string, unknown>;\n\n", .{ name, exported, name });
    }
    // emit's data: none for a void event (a rest tuple: TypeScript does not
    // let a generic void parameter be left out), optional when untyped.
    const emit_data = if (EventsOf(T) != null)
        "...data: [{[n]s}Events[K]] extends [void] ? [] : [data: {[n]s}Events[K]]): void"
    else
        "data?: {[n]s}Events[K]): void";
    const emit_body = if (EventsOf(T) != null) "plume.emit(name, ...data);" else "plume.emit(name, data);";
    const signatures = .{
        .{ "on", "listener: (data: {[n]s}Events[K]) => void): () => void", "return plume.on(name, listener);" },
        .{ "once", "listener: (data: {[n]s}Events[K]) => void): () => void", "return plume.once(name, listener);" },
        .{ "off", "listener?: (data: {[n]s}Events[K]) => void): void", "plume.off(name, listener);" },
        .{ "emit", emit_data, emit_body },
    };
    switch (kind) {
        .declarations => {
            try w.writeAll("/** The page runtime: events to and from Zig, and the desktop. */\ndeclare const Plume: PlumeDesktop & {\n");
            inline for (signatures) |s| {
                try w.print("  {s}<K extends keyof {s}Events>(name: K, ", .{ s[0], name });
                try w.print(s[1], .{ .n = name });
                try w.writeAll(";\n");
            }
            try w.writeAll("};\n");
        },
        .module => {
            try w.writeAll(
                \\
                \\const plume: any = (globalThis as any).Plume;
                \\
                \\/** The window, dialogs, clipboard, screens and menus. */
                \\export const Plume: PlumeDesktop = plume;
                \\
                \\/** Events to and from Zig (app.emit, app.on) and between the page's listeners. */
                \\export const Events = {
                \\
            );
            inline for (signatures) |s| {
                try w.print("  {s}<K extends keyof {s}Events>(name: K, ", .{ s[0], name });
                try w.print(s[1], .{ .n = name });
                try w.print(" {{ {s} }},\n", .{s[2]});
            }
            try w.writeAll("};\n");
        },
    }
}

/// `list` with the named types `X` uses (itself included), each once.
fn collect(comptime list: []const type, comptime X: type) []const type {
    if (X == Bytes) return list;
    switch (@typeInfo(X)) {
        .optional => |info| return collect(list, info.child),
        .pointer => |info| return switch (info.size) {
            .slice => if (info.child == u8) list else collect(list, info.child),
            .one => collect(list, info.child),
            else => list,
        },
        .array => |info| return if (info.child == u8) list else collect(list, info.child),
        .@"struct", .@"enum", .@"union" => {
            if (contains(list, X))
                return list;
            var result = list;
            if (isNamed(X))
                result = result ++ [_]type{X};
            switch (@typeInfo(X)) {
                .@"struct" => |info| for (info.field_types) |F| {
                    result = collect(result, F);
                },
                .@"union" => |info| for (info.field_types) |F| {
                    result = collect(result, F);
                },
                else => {},
            }
            return result;
        },
        else => return list,
    }
}

fn writeDeclaration(w: *Writer, comptime X: type, exported: []const u8) Writer.Error!void {
    switch (@typeInfo(X)) {
        .@"struct" => {
            try w.print("{s}interface {s} ", .{ exported, comptime typeName(X) });
            try writeObject(w, X, "\n", "  ");
            try w.writeAll("\n");
        },
        .@"enum" => {
            try w.print("{s}type {s} = ", .{ exported, comptime typeName(X) });
            try writeEnum(w, X);
            try w.writeAll(";\n");
        },
        .@"union" => {
            try w.print("{s}type {s} =", .{ exported, comptime typeName(X) });
            const info = @typeInfo(X).@"union";
            inline for (info.field_names, info.field_types) |field, F| {
                try w.writeAll("\n  | ");
                try writeVariant(w, field, F);
            }
            try w.writeAll(";\n");
        },
        else => unreachable,
    }
}

fn writeObject(w: *Writer, comptime X: type, comptime newline: []const u8, comptime indent: []const u8) Writer.Error!void {
    const info = @typeInfo(X).@"struct";
    try w.writeAll("{" ++ (if (newline.len > 0) newline else " "));
    inline for (info.field_names, info.field_types) |field, F| {
        try w.print(indent ++ "{s}: ", .{field});
        try writeType(w, F, false);
        try w.writeAll(";" ++ (if (newline.len > 0) newline else " "));
    }
    try w.writeAll("}");
}

fn writeEnum(w: *Writer, comptime X: type) Writer.Error!void {
    inline for (@typeInfo(X).@"enum".field_names, 0..) |field, i| {
        if (i > 0) try w.writeAll(" | ");
        try w.print("\"{s}\"", .{field});
    }
}

fn writeVariant(w: *Writer, comptime field: []const u8, comptime F: type) Writer.Error!void {
    try w.print("{{ tag: \"{s}\"", .{field});
    if (F != void) {
        try w.writeAll("; value: ");
        try writeType(w, F, false);
    }
    try w.writeAll(" }");
}

/// Whether the type is written with "|" at its top level (needs parentheses
/// before "[]").
fn isUnionLike(comptime X: type) bool {
    return switch (@typeInfo(X)) {
        .optional => true,
        .@"enum", .@"union" => !isNamed(X),
        else => false,
    };
}

/// `direct`: passed as an argument or sync result itself (not inside JSON),
/// where integers past 53 bits are BigInts.
fn writeType(w: *Writer, comptime X: type, comptime direct: bool) Writer.Error!void {
    if (X == Bytes) return w.writeAll(if (direct) "Uint8Array" else "number[]");
    switch (@typeInfo(X)) {
        .void => try w.writeAll("void"),
        .bool => try w.writeAll("boolean"),
        .int => |info| {
            const exact = if (info.signedness == .unsigned) info.bits <= 53 else info.bits <= 54;
            try w.writeAll(if (exact or !direct) "number" else "bigint");
        },
        .comptime_int, .float, .comptime_float => try w.writeAll("number"),
        .optional => |info| {
            if (info.child == Bytes) try writeType(w, Bytes, direct) else try writeElement(w, info.child);
            try w.writeAll(" | null");
        },
        .pointer => |info| switch (info.size) {
            .slice => if (info.child == u8) try w.writeAll("string") else {
                try writeElement(w, info.child);
                try w.writeAll("[]");
            },
            .one => switch (@typeInfo(info.child)) {
                .array => |array| if (array.child == u8) try w.writeAll("string") else try writeType(w, info.child, direct),
                else => try writeType(w, info.child, direct),
            },
            else => @compileError("no TypeScript type for " ++ @typeName(X)),
        },
        .array => |info| {
            try writeElement(w, info.child);
            try w.writeAll("[]");
        },
        .@"struct", .@"enum", .@"union" => if (isNamed(X)) try w.writeAll(comptime typeName(X)) else switch (@typeInfo(X)) {
            .@"struct" => try writeObject(w, X, "", ""),
            .@"enum" => try writeEnum(w, X),
            .@"union" => |info| inline for (info.field_names, info.field_types, 0..) |field, F, i| {
                if (i > 0) try w.writeAll(" | ");
                try writeVariant(w, field, F);
            },
            else => unreachable,
        },
        else => @compileError("no TypeScript type for " ++ @typeName(X)),
    }
}

fn writeElement(w: *Writer, comptime X: type) Writer.Error!void {
    if (isUnionLike(X)) {
        try w.writeAll("(");
        try writeType(w, X, false);
        try w.writeAll(")");
    } else try writeType(w, X, false);
}

