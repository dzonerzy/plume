/// Anonymous containers are written inline; named ones get a declaration.
fn isNamed(comptime X: type) bool {
    const type_name = @typeName(X);
    return switch (@typeInfo(X)) {
        .@"struct" => |info| !info.is_tuple and std.mem.indexOf(u8, type_name, "__struct_") == null,
        .@"enum" => std.mem.indexOf(u8, type_name, "__enum_") == null,
        .@"union" => std.mem.indexOf(u8, type_name, "__union_") == null,
        else => false,
    };
}

/// The TypeScript name of a named type: its last component, as an identifier.
fn typeName(comptime X: type) []const u8 {
    comptime {
        const full = @typeName(X);
        const short = if (std.mem.lastIndexOfScalar(u8, full, '.')) |dot| full[dot + 1 ..] else full;
        var result: [short.len]u8 = undefined;
        for (short, &result) |c, *slot|
            slot.* = if (std.ascii.isAlphanumeric(c) or c == '_') c else '_';
        const final = result;
        return &final;
    }
}

fn contains(comptime list: []const type, comptime X: type) bool {
    for (list) |item| {
        if (item == X) return true;
    }
    return false;
}

fn collectAll(comptime T: type, comptime bound: []const methods.Method) []const type {
    var list: []const type = &.{};
    for (bound) |method| {
        for (methods.jsParams(T, method.name)) |P| list = collect(list, P);
        list = collect(list, methods.Result(T, method.name));
    }
    if (EventsOf(T)) |E| {
        for (@typeInfo(E).@"struct".field_types) |F| list = collect(list, F);
    }
    return list;
}

/// The binding type's `pub const Events` struct, if it declares one.
fn EventsOf(comptime T: type) ?type {
    if (!@hasDecl(T, "Events")) return null;
    const E = T.Events;
    if (@TypeOf(E) != type or @typeInfo(E) != .@"struct")
        @compileError(@typeName(T) ++ ".Events is a struct: its fields name the events, their types the data");
    return E;
}

