//! plume-resources <plume.json> <executable name> <out-dir>: a Windows
//! application's resources besides its icon (plume's addApp), from
//! plume.json: version.rc (the version information Explorer's Details and
//! installers show) and app.manifest (per-monitor DPI as SDL sets it, common
//! controls 6, UTF-8, long paths). A build step, so plume.json's changes
//! reach the executable.

const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const a = init.arena.allocator();
    const io = init.io;
    const args = try init.minimal.args.toSlice(a);
    if (args.len != 4) {
        std.debug.print("usage: plume-resources <plume.json> <executable name> <out-dir>\n", .{});
        std.process.exit(2);
    }
    const cwd = std.Io.Dir.cwd();
    const text = cwd.readFileAlloc(io, args[1], a, .limited(1 << 20)) catch "{}";
    const info = Info.parse(a, text, args[2]);
    var out = try cwd.createDirPathOpen(io, args[3], .{});
    defer out.close(io);
    try out.writeFile(io, .{ .sub_path = "version.rc", .data = try info.versionResource(a) });
    try out.writeFile(io, .{ .sub_path = "app.manifest", .data = try info.manifest(a) });
}

const Info = struct {
    name: []const u8,
    title: []const u8,
    app_id: []const u8,
    version: []const u8,
    /// Major, minor, patch, build.
    numbers: [4]u16,
    publisher: []const u8,
    description: []const u8,
    copyright: []const u8,

    fn parse(a: std.mem.Allocator, text: []const u8, executable_name: []const u8) Info {
        const Json = struct {
            name: ?[]const u8 = null,
            title: ?[]const u8 = null,
            app_id: ?[]const u8 = null,
            version: []const u8 = "0.1.0",
            publisher: ?[]const u8 = null,
            description: ?[]const u8 = null,
            copyright: ?[]const u8 = null,
        };
        const json = std.json.parseFromSliceLeaky(Json, a, text, .{ .ignore_unknown_fields = true }) catch Json{};
        const name = json.name orelse executable_name;
        var numbers: [4]u16 = .{ 0, 0, 0, 0 };
        var parts = std.mem.tokenizeAny(u8, json.version, ".-+");
        for (&numbers) |*number| {
            const part = parts.next() orelse break;
            number.* = std.fmt.parseInt(u16, part, 10) catch break;
        }
        const publisher = json.publisher orelse name;
        return .{
            .name = name,
            .title = json.title orelse name,
            .app_id = json.app_id orelse std.fmt.allocPrint(a, "plume.{s}", .{name}) catch name,
            .version = json.version,
            .numbers = numbers,
            .publisher = publisher,
            .description = json.description orelse json.title orelse name,
            .copyright = json.copyright orelse std.fmt.allocPrint(a, "Copyright (C) {s}", .{publisher}) catch publisher,
        };
    }

    fn versionResource(info: Info, a: std.mem.Allocator) ![]const u8 {
        const n = info.numbers;
        return std.fmt.allocPrint(a,
            \\// Generated by plume's addApp from plume.json.
            \\1 VERSIONINFO
            \\FILEVERSION {d},{d},{d},{d}
            \\PRODUCTVERSION {d},{d},{d},{d}
            \\FILEFLAGSMASK 0x3F
            \\FILEFLAGS 0
            \\FILEOS 0x40004
            \\FILETYPE 1
            \\FILESUBTYPE 0
            \\BEGIN
            \\  BLOCK "StringFileInfo"
            \\  BEGIN
            \\    BLOCK "040904B0"
            \\    BEGIN
            \\      VALUE "CompanyName", "{s}"
            \\      VALUE "FileDescription", "{s}"
            \\      VALUE "FileVersion", "{s}"
            \\      VALUE "InternalName", "{s}"
            \\      VALUE "LegalCopyright", "{s}"
            \\      VALUE "OriginalFilename", "{s}.exe"
            \\      VALUE "ProductName", "{s}"
            \\      VALUE "ProductVersion", "{s}"
            \\    END
            \\  END
            \\  BLOCK "VarFileInfo"
            \\  BEGIN
            \\    VALUE "Translation", 0x409, 1200
            \\  END
            \\END
            \\
        , .{
            n[0],                                n[1],                                   n[2],                                n[3],
            n[0],                                n[1],                                   n[2],                                n[3],
            try rcString(a, info.publisher),     try rcString(a, info.description),      try rcString(a, info.version),       try rcString(a, info.name),
            try rcString(a, info.copyright),     try rcString(a, info.name),             try rcString(a, info.title),         try rcString(a, info.version),
        });
    }

    fn manifest(info: Info, a: std.mem.Allocator) ![]const u8 {
        const n = info.numbers;
        return std.fmt.allocPrint(a,
            \\<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
            \\<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
            \\  <assemblyIdentity type="win32" name="{s}" version="{d}.{d}.{d}.{d}" processorArchitecture="amd64"/>
            \\  <description>{s}</description>
            \\  <dependency>
            \\    <dependentAssembly>
            \\      <assemblyIdentity type="win32" name="Microsoft.Windows.Common-Controls" version="6.0.0.0" processorArchitecture="*" publicKeyToken="6595b64144ccf1df" language="*"/>
            \\    </dependentAssembly>
            \\  </dependency>
            \\  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
            \\    <application>
            \\      <supportedOS Id="{{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}}"/>
            \\    </application>
            \\  </compatibility>
            \\  <application xmlns="urn:schemas-microsoft-com:asm.v3">
            \\    <windowsSettings>
            \\      <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true/pm</dpiAware>
            \\      <dpiAwareness xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">PerMonitorV2</dpiAwareness>
            \\      <longPathAware xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">true</longPathAware>
            \\      <activeCodePage xmlns="http://schemas.microsoft.com/SMI/2019/WindowsSettings">UTF-8</activeCodePage>
            \\    </windowsSettings>
            \\  </application>
            \\  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">
            \\    <security>
            \\      <requestedPrivileges>
            \\        <requestedExecutionLevel level="asInvoker" uiAccess="false"/>
            \\      </requestedPrivileges>
            \\    </security>
            \\  </trustInfo>
            \\</assembly>
            \\
        , .{ try xmlText(a, info.app_id), n[0], n[1], n[2], n[3], try xmlText(a, info.description) });
    }
};

/// A resource script string's content: quotes doubled, no newlines.
fn rcString(a: std.mem.Allocator, text: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    for (text) |c| switch (c) {
        '"' => try out.appendSlice(a, "\"\""),
        '\r', '\n' => try out.append(a, ' '),
        else => try out.append(a, c),
    };
    return out.items;
}

fn xmlText(a: std.mem.Allocator, text: []const u8) ![]const u8 {
    var out: std.ArrayList(u8) = .empty;
    for (text) |c| switch (c) {
        '&' => try out.appendSlice(a, "&amp;"),
        '<' => try out.appendSlice(a, "&lt;"),
        '>' => try out.appendSlice(a, "&gt;"),
        '"' => try out.appendSlice(a, "&quot;"),
        else => try out.append(a, c),
    };
    return out.items;
}
